"""Namespaces and loading helpers shared by every part of the lab."""
from __future__ import annotations

from pathlib import Path

from rdflib import Graph, Namespace

ROOT = Path(__file__).resolve().parents[1]
BASE = "https://w3id.org/industrial-ontology-lab/"

MFG = Namespace(BASE + "core#")
PRD = Namespace(BASE + "production#")
MNT = Namespace(BASE + "maintenance#")
QA = Namespace(BASE + "quality#")
NRG = Namespace(BASE + "energy#")
INV = Namespace(BASE + "inventory#")
ID = Namespace(BASE + "id/")

PREFIXES = {"mfg": MFG, "prd": PRD, "mnt": MNT, "qa": QA, "nrg": NRG, "inv": INV, "id": ID}
DOMAINS = ["production", "maintenance", "quality", "energy", "inventory"]


def bind_all(g: Graph) -> Graph:
    for p, ns in PREFIXES.items():
        g.bind(p, ns)
    return g


def load_ontology(domains: list[str] | None = None) -> Graph:
    """Core plus the requested domain extensions (all by default)."""
    g = bind_all(Graph())
    g.parse(ROOT / "ontology" / "core.ttl")
    for d in DOMAINS if domains is None else domains:
        g.parse(ROOT / "ontology" / f"{d}.ttl")
    return g


def load_plant(with_ontology: bool = True) -> Graph:
    """Sample plant data (generated by lab.sample_data), optionally merged with the ontology."""
    g = load_ontology() if with_ontology else bind_all(Graph())
    g.parse(ROOT / "data" / "plant.ttl")
    return g


def query(g: Graph, sparql: str):
    """Run SPARQL with the lab prefixes already declared, return a list of dicts."""
    header = "\n".join(f"PREFIX {p}: <{ns}>" for p, ns in PREFIXES.items())
    header += "\nPREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>\nPREFIX xsd: <http://www.w3.org/2001/XMLSchema#>\n"
    res = g.query(header + sparql)
    return [{str(k): (v.toPython() if v is not None else None) for k, v in row.asdict().items()} for row in res]
